# SESSION 19 – GOOGLE (Belief Update)

# Step 1: Define values
prior = 0.7
observation = 0.6

# Step 2: Bayesian Update (simplified product rule)
updated_belief = prior * observation

# Step 3: Display results
print("Prior Belief:", prior)
print("Observation Likelihood:", observation)
print("Updated Belief:", updated_belief)

